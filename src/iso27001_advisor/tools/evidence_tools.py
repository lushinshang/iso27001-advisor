def generate_audit_evidence_checklist(clause_ids: List[str]) -> List[Dict]:
    """依 clause_id 清單回傳對應的稽核證據清單。

    Args:
        clause_ids: 條文 ID 清單，如 ['control_8.13', 'clause_9.2']。
                    大小寫不敏感；未知 ID 略過，不報錯。

    Returns:
        list of dict，每筆含 clause_id、clause_name、evidence（list[str]）。
        只回傳有對應資料的 clause_id。
    """
    result: List[Dict] = []
    for raw_id in clause_ids:
        normalized = raw_id.strip().lower()
        if normalized in EVIDENCE_MAP:
            entry = EVIDENCE_MAP[normalized]
            result.append({
                "clause_id": normalized,
                "clause_name": entry["name"],
                "evidence": list(entry["evidence"]),
            })
    return result
