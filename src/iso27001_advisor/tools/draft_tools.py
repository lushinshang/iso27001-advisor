def draft_gap_remediation(
    gap_result: Dict[str, Any],
    clause_ids: List[str],
) -> List[str]:
    """根據缺口分析結果產生補強建議。

    Args:
        gap_result: analyze_document_coverage() 的回傳值，
                    需含 "missing_signals" 欄位（list of dict，每筆含 "theme"）。
        clause_ids: 分析涉及的條文 ID 清單（目前保留供未來擴充，不影響主邏輯）。

    Returns:
        list[str]，每筆為一條補強建議。
        若無缺口，回傳通用維持建議。
    """
    missing_signals = gap_result.get("missing_signals", [])

    if not missing_signals:
        return ["文件已涵蓋主要要求，建議定期審查以維持持續符合性。"]

    suggestions: List[str] = []
    seen_themes = set()

    for signal in missing_signals:
        theme = signal.get("theme", "")
        if theme in seen_themes:
            continue
        seen_themes.add(theme)

        template = REMEDIATION_TEMPLATES.get(theme)
        if template:
            suggestions.append(template)
        else:
            # 無對應範本時，用 reason 產生通用建議
            reason = signal.get("reason", f"文件缺少 {theme} 相關說明")
            suggestions.append(f"建議補充 {theme} 相關政策或程序：{reason}")

    return suggestions
